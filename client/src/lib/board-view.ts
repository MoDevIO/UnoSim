import { type BoardId, DEFAULT_BOARD_ID } from "@shared/boards";

/**
 * The graphics of a board for the board view (plan P4.4): the board SVG, the overlay with the
 * interactive parts (ids `pin-<n>-click`, `pin-A<k>-…`, `led-l|on|tx|rx`, `reset-click`) and the
 * size of the drawing without its safe margin, which the view scales to the available space.
 */
export interface BoardView {
  readonly boardSvg: string;
  readonly overlaySvg: string;
  readonly width: number;
  readonly height: number;
  /** Where the TH Köln mark sits, in percent of the drawing; the position on the Uno when absent. */
  readonly logo?: { readonly left: number; readonly top: number; readonly width: number; readonly height: number };
}

/** The mark's place on the Uno (and the Nano): on the lower right of the ATmega chip. */
export const DEFAULT_LOGO_PLACEMENT = { left: 70, top: 66, width: 24, height: 8 } as const;

const UNO_VIEW: BoardView = { boardSvg: "/ArduinoUno.svg", overlaySvg: "/ArduinoUno-overlay.svg", width: 285.2, height: 209 };
// Generated by scripts/generate-nano-svg.mjs: 43.2 x 18 mm at 4 units per mm.
const NANO_VIEW: BoardView = { boardSvg: "/ArduinoNano.svg", overlaySvg: "/ArduinoNano-overlay.svg", width: 172.8, height: 72 };

// Generated by scripts/generate-mega-svg.mjs: 101.6 x 53.3 mm at 4 units per mm.
// The mark sits in the free area between the chip and the right header, clear of the board's own labels.
const MEGA_VIEW: BoardView = {
  boardSvg: "/ArduinoMega.svg", overlaySvg: "/ArduinoMega-overlay.svg", width: 406.4, height: 213.2,
  logo: { left: 74, top: 38, width: 20, height: 10 },
};

const VIEWS: Partial<Record<BoardId, BoardView>> = { uno: UNO_VIEW, nano: NANO_VIEW, mega2560: MEGA_VIEW };

/** The view of a board; a board without graphics yet (ATtiny85) is drawn as the Uno. */
export function boardView(board: BoardId = DEFAULT_BOARD_ID): BoardView {
  return VIEWS[board] ?? UNO_VIEW;
}
