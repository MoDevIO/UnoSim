// Spike P0.6 – generate 5 × 30000 bytes of PROGMEM so that code lands above 128 KB.
// Usage: node spikes/p0-6/gen-bigdata.mjs <out.h>
import { writeFileSync } from "node:fs";
export const ARRAYS = 5, LENGTH = 30000;
export const value = (k, i) => (i * 31 + k * 7) & 0xff;
const out = process.argv[2];
if (out) {
  let h = "// Generated by gen-bigdata.mjs – do not edit.\n#include <avr/pgmspace.h>\n";
  for (let k = 0; k < ARRAYS; k++) {
    const vals = Array.from({ length: LENGTH }, (_, i) => value(k, i));
    h += `const uint8_t big${k}[${LENGTH}] PROGMEM = {${vals.join(",")}};\n`;
  }
  writeFileSync(out, h);
}
